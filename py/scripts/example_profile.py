"""Write docs/example_profile.md: what the v1 default readers return for one invented person.

    cd py && uv run python scripts/example_profile.py

The person is aas.example.synthetic_person(): invented writing and an invented year of plays, no real data.
A second, thin version of the same person (a few posts, a few weeks of plays) shows the refusals.
"""

from __future__ import annotations

from collections import Counter
from datetime import date
from pathlib import Path

from aas import example
from aas import profile as P
from aas.person import Person

OUT = Path(__file__).resolve().parents[1] / "docs" / "example_profile.md"


def _counts(p: Person) -> str:
    c = Counter((t.source, t.kind) for t in p.texts)
    words = sum(len(t.text.split()) for t in p.texts if t.kind != "search")
    label = {("reddit", "comment"): "Reddit comments", ("x", "tweet"): "posts on X", ("blog", "blog"): "blog post(s)",
             ("google_search", "search"): "searches"}
    parts = [f"{n} {label.get(k, f'{k[1]} items from {k[0]}')}" for k, n in sorted(c.items(), key=lambda kv: -kv[1])]
    days = (max(x.when for x in p.plays) - min(x.when for x in p.plays)).days if p.plays else 0
    return (f"{', '.join(parts)} ({words:,} words not counting searches), and "
            f"{len(p.plays):,} plays over {days} days.")


def _table(prof: P.Profile) -> list[str]:
    L = ["| reader | trait | value | 80% interval | stated validity |", "|---|---|---|---|---|"]
    for e in prof.estimates:
        if e.kind == "measured":
            continue
        iv = "none" if e.low is None else f"{e.low:+.2f} to {e.high:+.2f}"
        val = "untested" if e.validity is None else f"{e.validity_kind} {e.validity:.2f}"
        L.append(f"| {e.reader} | {e.trait} | {e.value:+.3f} | {iv} | {val} |")
    return L


def thin(p: Person) -> Person:
    """The same person with five posts on X and two weeks of listening."""
    texts = [t for t in p.texts if t.source == "x"][:5]
    plays = [x for x in p.plays if (x.when - p.plays[0].when).days < 14]
    return Person(texts=texts, plays=plays, sources=["x (synthetic)", "spotify extended history (synthetic)"],
                  notes=list(p.notes))


def main() -> None:
    person = example.synthetic_person()
    readers = example.default_readers()
    prof = P.build(person, readers)
    small = thin(person)
    prof_small = P.build(small, example.default_readers())
    refused = [u for u in prof.unread]
    L = [
        "# What v1 returns for one person",
        "",
        f"Generated by `scripts/example_profile.py` on {date.today().isoformat()}. Re-running it rewrites this page.",
        "",
        "The person here is invented. Every post, comment, search, artist and play was written or generated for "
        "`src/aas/example.py`, and no real person's data went in. They are a hospital pharmacist who works shifts, "
        "rides a bike, bakes bread and fixes old bicycles, and they brought " + _counts(person),
        "",
        "The readers are the v1 defaults (`aas.example.default_readers`): text Big Five (bag of words trained on "
        "student essays), text MBTI (trained on a typology forum), the music reader, and the zero-data fused reader "
        "over the two text readers. The distilled text reader is not run, because it failed its pre-registered test "
        "(`distill.md`). Music is described on its own and never fused, since no link from listening to the Big Five "
        "has been tested.",
        "",
        "## Reading it",
        "",
        "Big Five values are z scores against the quiz norms, so 0 is average and about plus or minus 1 covers two "
        "people in three. Each interval claims to contain the person's quiz z 80% of the time. On this kind of "
        "writing the text readers state an accuracy close to chance (AUC 0.55 to 0.57 for this mix of writing, r about 0.11 to 0.16), so "
        "every Big Five interval is nearly as wide as the one that fits anybody (plus or minus 1.28), and every "
        "value sits close to 0. That is what v1 gives someone who mostly writes Reddit comments and posts on X. MBTI values are the chance of the first letter, pulled toward 50% to match an off-forum "
        "accuracy that is inferred and untested. The fused reader leaves `validity` empty because fusion has never "
        "been tested on real people with several sources. Its evidence gives the accuracy the model implies for the "
        "sources it combined, after the 0.75 discount.",
        "",
        "Openness has no text Big Five number. The reader has only been shown to read openness from essay-like "
        "prose, and that is 22% of this person's words where at least half is needed. Openness still gets a fused "
        "value, from the MBTI N/S letter alone.",
        "",
        "## Estimates",
        "",
        *_table(prof),
        "",
        f"Readers that spoke: {', '.join(prof.readers_run)}. Things they declined to say: {len(refused)}.",
        "",
        "## Full dump",
        "",
        "`profile.dump()`, unedited:",
        "",
        "```",
        P.dump(prof).rstrip(),
        "```",
        "",
        "## The same person with very little data",
        "",
        f"Here the person brings only their first five posts on X ({sum(len(t.text.split()) for t in small.texts)} "
        f"words) and their first two weeks of listening ({len(small.plays):,} plays). Text MBTI and music decline "
        "and say why. Text Big Five still answers, because its floor is 25 words, but at this length on tweets it "
        "states an AUC of 0.53 to 0.54 and its intervals are the width that fits anybody.",
        "",
        "```",
        P.dump(prof_small).rstrip(),
        "```",
        "",
    ]
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
